def project_assessment(project: Project) -> dict[str, Any]:
    """То же, что возвращает Claude, только без ИИ: решение классификатора и шаблонный отклик."""
    verdict = project.verdict or classify(project.title, project.description)
    key = verdict.skill_keys[0] if verdict.skill_keys else ""
    intro, ask = REPLY_TEMPLATES.get(key, DEFAULT_REPLY)
    reply = f"Здравствуйте! {intro}\n{ask}\nМогу начать сразу после уточнения деталей."
    return {
        "can_do": verdict.ok,
        "confidence": None,
        "size": "",
        "summary": project.title,
        "human_steps": HUMAN_STEPS_RUN if key in RUNS_CODE else HUMAN_STEPS,
        "risks": "",
        "draft_reply": reply,
        "source": "templates",
    }



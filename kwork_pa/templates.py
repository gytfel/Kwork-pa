def lead_pitch(lead: Lead) -> str:
    company = lead.company
    observation = "Хочу предложить помощь с сайтом"
    for problem in lead.problems:
        match = next((text for prefix, text in OBSERVATIONS if problem.startswith(prefix)), None)
        if match:
            observation = match
            break
    phrases = [CUSTOMER_PHRASES.get(s, s[:1].lower() + s[1:]) for s in lead.services[:2]]
    services = " и ".join(phrases) if len(phrases) == 2 else (phrases[0] if phrases else "сделать сайт")
    return (
        f"Здравствуйте! Это по поводу «{company.name}» в 2ГИС. {observation}.\n"
        f"Могу помочь: {services}.\n"
        "Если интересно — расскажу, как это может выглядеть, и покажу примеры."
    )
